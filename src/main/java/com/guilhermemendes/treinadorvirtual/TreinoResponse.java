package com.guilhermemendes.treinadorvirtual;

public class TreinoResponse {
    private String planilha;
    private String rota;
    private String clima;

    public String getPlanilha() { return planilha; }
    public void setPlanilha(String planilha) { this.planilha = planilha; }

    public String getRota() { return rota; }
    public void setRota(String rota) { this.rota = rota; }

    public String getClima() { return clima; }
    public void setClima(String clima) { this.clima = clima; }
}